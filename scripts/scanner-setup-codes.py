#!/usr/bin/env python3
"""Regenerate frontend/src/scannerSetupCodes.ts: Eyoyo EYH2 setup QR codes, decoded from its manual."""
import json
from pathlib import Path

import zxingcpp

# Applied in this order on the kiosk's Scanner setup screen.
CODES = [
    ("Restore defaults", "Clears every earlier setting.", "@WSM00010000."),
    ("End character: CR", "Each scan ends with Enter, which the kiosk needs.", "@WSM05040001."),
    ("Low volume", "Quiet beep for shared lab space.", "@WSM04010000."),
]


def svg_path(text):
    bitmap = zxingcpp.write_barcode_to_image(zxingcpp.create_barcode(text, zxingcpp.BarcodeFormat.QRCode),
                                             scale=1, add_hrt=False, add_quiet_zones=True)
    view = memoryview(bitmap)
    height, width = view.shape
    raw = view.tobytes()
    return width, "".join(f"M{x} {y}h1v1h-1z" for y in range(height) for x in range(width) if raw[y * width + x] < 128)


entries = []
for label, note, payload in CODES:
    size, path = svg_path(payload)
    entries.append({"label": label, "note": note, "payload": payload, "size": size, "path": path})
target = Path(__file__).resolve().parents[1] / "frontend" / "src" / "scannerSetupCodes.ts"
target.write_text("// Generated by scripts/scanner-setup-codes.py from the Eyoyo EYH2 manual. Do not edit.\n"
                  "export const SCANNER_SETUP_CODES = " + json.dumps(entries, indent=2) + " as const\n")
print(f"Wrote {len(entries)} codes to {target}")
